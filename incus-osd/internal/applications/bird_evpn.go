// birdMinimalHeader starts the minimal bird.conf generated when there is no raw configuration.
const birdMinimalHeader = "# Minimal configuration, generated by IncusOS as the bird application has no configuration of its own.\n"

// birdEVPNHeader starts the generated part of bird.conf.
const birdEVPNHeader = "# ---- BGP EVPN, generated by IncusOS from the network configuration (vtep, vxlans) and the evpn settings ----\n"

var birdIdentRegex = regexp.MustCompile(`[^A-Za-z0-9_]`)

// birdIdent turns a name into a BIRD identifier.
func birdIdent(name string) string {
	return birdIdentRegex.ReplaceAllString(name, "_")
}

// birdRouteTarget formats an <asn>:<number> route target for BIRD.
func birdRouteTarget(rt string) (string, error) {
	asn, number, found := strings.Cut(rt, ":")
	if !found {
		return "", fmt.Errorf("route target %q isn't <asn>:<number>", rt)
	}

	asnValue, err := strconv.ParseUint(asn, 10, 32)
	if err != nil {
		return "", fmt.Errorf("route target %q has an invalid AS number", rt)
	}

	// A 4 byte AS number leaves 16 bits for the number, a 2 byte one 32 bits.
	numberBits := 32
	if asnValue > 65535 {
		numberBits = 16
	}

	_, err = strconv.ParseUint(number, 10, numberBits)
	if err != nil {
		return "", fmt.Errorf("route target %q has an invalid number", rt)
	}

	return fmt.Sprintf("(rt, %s, %s)", asn, number), nil
}

// birdEVPNConfig generates the BIRD configuration of the VXLANs in the network configuration. An empty string
// means that EVPN isn't configured.
func birdEVPNConfig(netCfg *api.SystemNetworkConfig, evpn *api.ApplicationBirdEVPN) (string, error) {
	if evpn == nil {
		return "", nil
	}

	if evpn.ASN == 0 {
		return "", errors.New("evpn needs an asn")
	}

	if evpn.ReceiveLimit < 0 {
		return "", errors.New("evpn receive_limit can't be negative")
	}

	var vxlans []api.SystemNetworkVXLAN
	if netCfg != nil {
		vxlans = netCfg.EffectiveVXLANs()
	}

	if len(vxlans) == 0 {
		return "", errors.New("evpn needs vxlans in the network configuration")
	}

	// One VTEP: the BGP sessions, the route distinguishers and the IMET routes use its address.
	vtep := vxlans[0].Local
	for _, vxlan := range vxlans {
		if vxlan.Local != vtep {
			return "", fmt.Errorf("evpn needs all vxlans on one local address, vxlan %s uses %s and not %s", vxlan.Name, vxlan.Local, vtep)
		}
	}

	vtepAddr, err := netip.ParseAddr(vtep)
	if err != nil || !vtepAddr.Is4() {
		// IP-form route distinguishers only exist for IPv4.
		return "", fmt.Errorf("evpn needs an IPv4 vtep address, not %q", vtep)
	}

	rtASN := evpn.RouteTargetASN
	if rtASN == 0 {
		rtASN = evpn.ASN
	}

	// The VTEPs that may be tunnel endpoints are the firewall sources of the VXLANs.
	vtepPrefixes := []string{}

	for _, vxlan := range vxlans {
		for _, source := range vxlan.FirewallSources {
			prefix, err := netip.ParsePrefix(source)
			if err != nil {
				addr, err := netip.ParseAddr(source)
				if err != nil {
					return "", fmt.Errorf("vxlan %s has an invalid firewall source %q", vxlan.Name, source)
				}

				prefix = netip.PrefixFrom(addr, addr.BitLen())
			}

			if !slices.Contains(vtepPrefixes, prefix.Masked().String()) {
				vtepPrefixes = append(vtepPrefixes, prefix.Masked().String())
			}
		}
	}

	var b strings.Builder

	b.WriteString(birdEVPNHeader)
	b.WriteString("evpn table incusos_evpn;\n")

	vnis := map[int]string{}

	addVNI := func(vni int, what string) error {
		if vni < 1 || vni > 16777215 {
			return fmt.Errorf("%s: vni %d must be between 1 and 16777215", what, vni)
		}

		if other, ok := vnis[vni]; ok {
			return fmt.Errorf("%s: vni %d is already used by %s", what, vni, other)
		}

		vnis[vni] = what

		return nil
	}

	writeBridge := func(name string) {
		ident := birdIdent(name)

		fmt.Fprintf(&b, "\neth table incusos_eth_%s;\n", ident)
		fmt.Fprintf(&b, "protocol bridge incusos_br_%s {\n", ident)
		b.WriteString("  # A MAC the kernel learns on the VXLAN port has moved away (live migration): the old host withdraws.\n")
		b.WriteString("  # preference 200 beats EVPN, so a MAC learned locally is advertised at once.\n")
		b.WriteString("  eth {\n")
		fmt.Fprintf(&b, "    table incusos_eth_%s;\n", ident)
		b.WriteString("    preference 200;\n")
		fmt.Fprintf(&b, "    import filter { if ifname = \"_x%s\" then reject; accept; };\n", name)
		b.WriteString("    export all;\n")
		b.WriteString("  };\n")
		fmt.Fprintf(&b, "  bridge device \"%s\";\n", name)
		b.WriteString("}\n")
	}

	writeEVPN := func(name string, rd string, rt string, vni int) {
		ident := birdIdent(name)

		fmt.Fprintf(&b, "protocol evpn incusos_evpn_%s {\n", ident)
		fmt.Fprintf(&b, "  eth { table incusos_eth_%s; };\n", ident)
		b.WriteString("  evpn { table incusos_evpn; };\n")
		fmt.Fprintf(&b, "  rd %s;\n", rd)
		fmt.Fprintf(&b, "  route target %s;\n", rt)
		fmt.Fprintf(&b, "  encapsulation vxlan { tunnel device \"_x%s\"; router address %s; };\n", name, vtep)
		fmt.Fprintf(&b, "  vni %d;\n", vni)
		b.WriteString("}\n")
	}

	// Route targets other than the automatic one.
	routeTargets := map[string]string{}

	for _, override := range evpn.RouteTargets {
		index := slices.IndexFunc(vxlans, func(v api.SystemNetworkVXLAN) bool { return v.Name == override.VXLAN })
		if index < 0 {
			return "", fmt.Errorf("evpn route target for vxlan %q: the vxlan doesn't exist", override.VXLAN)
		}

		if vxlans[index].VRF != "" {
			return "", fmt.Errorf("evpn route target for vxlan %q: a vxlan in a vrf gets no evpn instance", override.VXLAN)
		}

		_, ok := routeTargets[override.VXLAN]
		if ok {
			return "", fmt.Errorf("evpn route target for vxlan %q: set more than once", override.VXLAN)
		}

		rt, err := birdRouteTarget(override.RouteTarget)
		if err != nil {
			return "", fmt.Errorf("evpn route target for vxlan %q: %w", override.VXLAN, err)
		}

		routeTargets[override.VXLAN] = rt
	}

	for _, vxlan := range vxlans {
		what := "vxlan " + vxlan.Name

		err := addVNI(vxlan.VNI, what)
		if err != nil {
			return "", err
		}

		if vxlan.VRF != "" {
			fmt.Fprintf(&b, "\n# vxlan %s: VNI %d in VRF %s, a layer 3 VNI. BIRD can't originate or install EVPN type 5 routes yet.\n", vxlan.Name, vxlan.VNI, vxlan.VRF)

			continue
		}

		// RD <vtep>:<vni>, so the VNI must fit the 16 bit number of an IP-form RD. A VNI is used once, so is
		// the RD.
		if vxlan.VNI > 65535 {
			return "", fmt.Errorf("%s: vni %d doesn't fit the route distinguisher <vtep>:<vni>, use a vni up to 65535", what, vxlan.VNI)
		}

		rt, ok := routeTargets[vxlan.Name]
		if !ok {
			rt, err = birdRouteTarget(fmt.Sprintf("%d:%d", rtASN, vxlan.VNI))
			if err != nil {
				return "", fmt.Errorf("%s: automatic %w", what, err)
			}
		}

		writeBridge(vxlan.Name)
		writeEVPN(vxlan.Name, fmt.Sprintf("%s:%d", vtep, vxlan.VNI), rt, vxlan.VNI)
	}

	// Only routes whose tunnel endpoint may send VXLAN traffic: type 2 uses the BGP next hop, type 3 (IMET)
	// carries the VTEP as router IP. BIRD can't match an ip against a prefix set (the filter fails at runtime and
	// rejects the route), so the check is a function of single prefix matches.
	b.WriteString("\n")

	if len(vtepPrefixes) > 0 {
		b.WriteString("function incusos_is_vtep(ip a) -> bool\n{\n  return ")

		for i, prefix := range vtepPrefixes {
			if i > 0 {
				b.WriteString(" || ")
			}

			fmt.Fprintf(&b, "a ~ %s", prefix)
		}

		b.WriteString(";\n}\n")
	}

	b.WriteString("filter incusos_evpn_in {\n")

	if len(vtepPrefixes) > 0 {
		b.WriteString("  if !incusos_is_vtep(bgp_next_hop) then reject;\n")
		b.WriteString("  if net.evpn_type = NET_EVPN_IMET && !incusos_is_vtep(net.router_ip) then reject;\n")
	}

	b.WriteString("  # BIRD maps a MAC+IP type 2 route onto the MAC-only route of the same RD: withdrawing it would remove the MAC.\n")
	b.WriteString("  if net.evpn_type = NET_EVPN_MAC && net.ip != :: then reject;\n")
	b.WriteString("  accept;\n")
	b.WriteString("}\n")

	// Only the own routes are exported: re-exporting learned routes over eBGP would make this host their next hop.
	b.WriteString("\ntemplate bgp incusos_evpn_peer {\n")
	fmt.Fprintf(&b, "  local %s as %d;\n", vtep, evpn.ASN)
	b.WriteString("  multihop;\n")

	if evpn.BFD {
		b.WriteString("  bfd on;\n")
	}

	b.WriteString("  evpn {\n")
	b.WriteString("    table incusos_evpn;\n")
	b.WriteString("    import filter incusos_evpn_in;\n")

	if evpn.ReceiveLimit > 0 {
		fmt.Fprintf(&b, "    receive limit %d action block;\n", evpn.ReceiveLimit)
	}

	b.WriteString("    export filter { if source = RTS_BGP then reject; accept; };\n")
	b.WriteString("  };\n")
	b.WriteString("}\n")

	names := []string{}

	for _, peer := range evpn.Peers {
		if peer.Name == "" {
			return "", errors.New("evpn peer without a name")
		}

		ident := birdIdent(peer.Name)
		if slices.Contains(names, ident) {
			return "", fmt.Errorf("evpn peer %q: the name is already used", peer.Name)
		}

		names = append(names, ident)

		_, err := netip.ParseAddr(peer.Address)
		if err != nil {
			return "", fmt.Errorf("evpn peer %q: invalid address %q", peer.Name, peer.Address)
		}

		if peer.ASN == 0 {
			return "", fmt.Errorf("evpn peer %q needs an asn", peer.Name)
		}

		fmt.Fprintf(&b, "protocol bgp incusos_evpn_%s from incusos_evpn_peer { neighbor %s as %d; }\n", ident, peer.Address, peer.ASN)
	}

	return b.String(), nil
}

// birdFullConfig returns the bird.conf to write: the raw configuration and the generated EVPN part. Without a raw
// configuration, a minimal one (router ID, device and direct protocols) carries the EVPN part.
func birdFullConfig(raw string, netCfg *api.SystemNetworkConfig, evpn *api.ApplicationBirdEVPN) (string, error) {
	generated, err := birdEVPNConfig(netCfg, evpn)
	if err != nil {
		return "", err
	}

	if generated == "" {
		return raw, nil
	}

	if strings.TrimSpace(raw) == "" {
		vtep := netCfg.EffectiveVXLANs()[0].Local

		raw = birdMinimalHeader +
			"router id " + vtep + ";\n" +
			"protocol device { }\n" +
			"# The routes to the other VTEPs, so the EVPN next hops resolve.\n" +
			"protocol direct { ipv4; ipv6; }\n"
	}

	return strings.TrimRight(raw, "\n") + "\n\n" + generated, nil
}

// birdEVPNProtocols returns the generated EVPN protocols of a bird.conf by name, each with its block.
func birdEVPNProtocols(cfg string) map[string]string {
	ret := map[string]string{}

	_, generated, found := strings.Cut(cfg, birdEVPNHeader)
	if !found {
		return ret
	}

	for _, block := range strings.Split(generated, "\nprotocol evpn ")[1:] {
		name, _, _ := strings.Cut(block, " ")
		body, _, _ := strings.Cut(block, "\n}\n")
		ret[name] = body
	}

	return ret
}

// changedBirdEVPNProtocols returns the generated EVPN protocols present in both configurations whose block
// changed.
func changedBirdEVPNProtocols(oldCfg string, newCfg string) []string {
	oldProtocols := birdEVPNProtocols(oldCfg)
	ret := []string{}

	for name, body := range birdEVPNProtocols(newCfg) {
		oldBody, ok := oldProtocols[name]
		if ok && oldBody != body {
			ret = append(ret, name)
		}
	}

	slices.Sort(ret)

	return ret
}
